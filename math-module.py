import math
# math.ceil()
x = 10.5
print(math.ceil(x)) #output .... 11 >>> forward 10.5 to 11

# math.fabs()
x = -10
print(math.fabs(x)) #output .... 10.0

# math.factorial()
x = 5
print(math.factorial(x)) #output .... 120

#  math.floor()
x = 10.5
print(math.floor(x))  #output .... 10 >>> backward 10.5 to 10

# math.fsum()
list = [10 , 20 , 30 , 40 , 50 ]
print(math.fsum(list))  #output ... 150.0 >>> sum of all values in list

# math.sqrt()
x = 16
print(math.sqrt(x)) #output ... 4.0 >>> 16 is sqrt of 16

